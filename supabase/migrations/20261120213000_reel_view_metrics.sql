BEGIN;

CREATE INDEX IF NOT EXISTS comments_reel_target_count_idx
  ON public.comments (target_id)
  WHERE target_type = 'reel';

CREATE TABLE IF NOT EXISTS public.reel_views (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reel_id bigint NOT NULL REFERENCES public.reels(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  viewed_at timestamptz NOT NULL DEFAULT now(),
  view_day date NOT NULL DEFAULT ((now() AT TIME ZONE 'UTC')::date)
);

CREATE UNIQUE INDEX IF NOT EXISTS reel_views_one_per_user_daily_uidx
  ON public.reel_views (reel_id, user_id, view_day);
CREATE INDEX IF NOT EXISTS reel_views_reel_idx ON public.reel_views (reel_id);

ALTER TABLE public.reel_views ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS reel_views_count_read ON public.reel_views;
CREATE POLICY reel_views_count_read ON public.reel_views
  FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS reel_views_insert_own ON public.reel_views;
CREATE POLICY reel_views_insert_own ON public.reel_views
  FOR INSERT TO authenticated
  WITH CHECK ((SELECT auth.uid()) = user_id);

REVOKE ALL ON TABLE public.reel_views FROM PUBLIC, anon, authenticated;
GRANT SELECT (reel_id) ON TABLE public.reel_views TO anon, authenticated;
GRANT INSERT (reel_id, user_id) ON TABLE public.reel_views TO authenticated;

CREATE OR REPLACE VIEW public.reel_view_counts
WITH (security_invoker = true)
AS
SELECT reel_id, COUNT(*)::bigint AS views_count
FROM public.reel_views
GROUP BY reel_id;

CREATE OR REPLACE VIEW public.reel_comment_counts
WITH (security_invoker = true)
AS
SELECT target_id AS reel_id, COUNT(*)::bigint AS comments_count
FROM public.comments
WHERE target_type = 'reel'
GROUP BY target_id;

REVOKE ALL ON TABLE public.reel_view_counts FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.reel_comment_counts FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.reel_view_counts TO anon, authenticated;
GRANT SELECT ON TABLE public.reel_comment_counts TO anon, authenticated;

COMMENT ON TABLE public.reel_views IS
  'Daily-deduplicated reel view ledger. Viewer identities remain unselectable; only reel_id can be read.';
COMMENT ON VIEW public.reel_view_counts IS
  'Daily-deduplicated reel view totals; SECURITY INVOKER preserves table RLS.';
COMMENT ON VIEW public.reel_comment_counts IS
  'Reel comment totals; SECURITY INVOKER preserves comments table RLS.';

NOTIFY pgrst, 'reload schema';
COMMIT;
