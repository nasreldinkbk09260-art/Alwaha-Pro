-- Alwaha-Pro marketplace lifecycle, optional distance search, buyer feedback and safety reports.
-- Additive-only migration: preserves existing products and existing public seller IDs.
BEGIN;

ALTER TABLE public.products ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'active';
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS location_label text NOT NULL DEFAULT '';
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS latitude double precision;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS longitude double precision;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS promoted_until timestamptz;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS archived_at timestamptz;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS sold_at timestamptz;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS sold_to uuid REFERENCES auth.users(id) ON DELETE SET NULL;

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'products_status_allowed' AND conrelid = 'public.products'::regclass) THEN
    ALTER TABLE public.products ADD CONSTRAINT products_status_allowed CHECK (status IN ('active','sold','archived'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'products_geo_bounds' AND conrelid = 'public.products'::regclass) THEN
    ALTER TABLE public.products ADD CONSTRAINT products_geo_bounds CHECK (
      (latitude IS NULL AND longitude IS NULL) OR
      (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180)
    );
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS products_status_created_idx ON public.products(status, created_at DESC);
CREATE INDEX IF NOT EXISTS products_geo_idx ON public.products(latitude, longitude) WHERE status = 'active' AND latitude IS NOT NULL AND longitude IS NOT NULL;
CREATE INDEX IF NOT EXISTS products_promoted_until_idx ON public.products(promoted_until DESC) WHERE promoted_until IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.marketplace_reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  seller_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  reviewer_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  rating smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
  review text NOT NULL DEFAULT '' CHECK (char_length(review) <= 1000),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT marketplace_reviews_one_per_buyer UNIQUE (product_id, reviewer_id),
  CONSTRAINT marketplace_reviews_not_self CHECK (reviewer_id <> seller_id)
);
CREATE INDEX IF NOT EXISTS marketplace_reviews_seller_created_idx ON public.marketplace_reviews(seller_id, created_at DESC);
ALTER TABLE public.marketplace_reviews ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.marketplace_reviews FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.marketplace_reviews TO anon, authenticated;
GRANT INSERT, DELETE ON TABLE public.marketplace_reviews TO authenticated;
DROP POLICY IF EXISTS marketplace_reviews_read_public ON public.marketplace_reviews;
CREATE POLICY marketplace_reviews_read_public ON public.marketplace_reviews FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS marketplace_reviews_insert_verified_buyer ON public.marketplace_reviews;
CREATE POLICY marketplace_reviews_insert_verified_buyer ON public.marketplace_reviews FOR INSERT TO authenticated
  WITH CHECK (
    reviewer_id = (SELECT auth.uid())
    AND reviewer_id <> seller_id
    AND EXISTS (
      SELECT 1 FROM public.products p
      WHERE p.id = product_id
        AND p.seller_id = seller_id
        AND p.status = 'sold'
        AND p.sold_to = (SELECT auth.uid())
    )
  );
DROP POLICY IF EXISTS marketplace_reviews_delete_own ON public.marketplace_reviews;
CREATE POLICY marketplace_reviews_delete_own ON public.marketplace_reviews FOR DELETE TO authenticated
  USING (reviewer_id = (SELECT auth.uid()));

CREATE TABLE IF NOT EXISTS public.marketplace_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  seller_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  reporter_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  reason text NOT NULL CHECK (char_length(trim(reason)) BETWEEN 1 AND 1000),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','reviewing','resolved','dismissed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz,
  CONSTRAINT marketplace_reports_not_self CHECK (reporter_id <> seller_id)
);
CREATE INDEX IF NOT EXISTS marketplace_reports_status_created_idx ON public.marketplace_reports(status, created_at DESC);
ALTER TABLE public.marketplace_reports ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.marketplace_reports FROM PUBLIC, anon, authenticated;
GRANT INSERT ON TABLE public.marketplace_reports TO authenticated;
GRANT SELECT ON TABLE public.marketplace_reports TO authenticated;
GRANT UPDATE (status, reviewed_at) ON TABLE public.marketplace_reports TO authenticated;
DROP POLICY IF EXISTS marketplace_reports_insert_own ON public.marketplace_reports;
CREATE POLICY marketplace_reports_insert_own ON public.marketplace_reports FOR INSERT TO authenticated
  WITH CHECK (
    reporter_id = (SELECT auth.uid())
    AND reporter_id <> seller_id
    AND EXISTS (SELECT 1 FROM public.products p WHERE p.id = product_id AND p.seller_id = seller_id)
  );
DROP POLICY IF EXISTS marketplace_reports_select_reporter_or_admin ON public.marketplace_reports;
CREATE POLICY marketplace_reports_select_reporter_or_admin ON public.marketplace_reports FOR SELECT TO authenticated
  USING (
    reporter_id = (SELECT auth.uid())
    OR public.is_admin()
  );
DROP POLICY IF EXISTS marketplace_reports_admin_update ON public.marketplace_reports;
CREATE POLICY marketplace_reports_admin_update ON public.marketplace_reports FOR UPDATE TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

COMMIT;
