-- Minimal PostgreSQL fixture for CI-only validation of the marketplace migrations.
-- Supabase-specific auth/realtime schemas and cron API are stubbed; no production data is used.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN CREATE ROLE anon NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN CREATE ROLE authenticated NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN CREATE ROLE service_role NOLOGIN BYPASSRLS; END IF;
END $$;

CREATE SCHEMA auth;
CREATE TABLE auth.users (id uuid PRIMARY KEY);
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT nullif(current_setting('request.jwt.claim.sub', true),'')::uuid
$$;

CREATE SCHEMA realtime;
CREATE TABLE realtime.messages (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, topic text, extension text NOT NULL DEFAULT 'broadcast');
CREATE FUNCTION realtime.topic() RETURNS text LANGUAGE sql STABLE AS $$
  SELECT current_setting('realtime.topic', true)
$$;

-- Mock pg_cron metadata/API for CI. The real pg_cron extension is enabled only by
-- the production migration; this fixture tests the daily scheduling call contract.
CREATE SCHEMA cron;
CREATE TABLE cron.job (
  jobid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  jobname text UNIQUE NOT NULL,
  schedule text NOT NULL,
  command text NOT NULL,
  active boolean NOT NULL DEFAULT true
);
CREATE FUNCTION cron.unschedule(p_job_id bigint) RETURNS boolean LANGUAGE plpgsql AS $$
BEGIN DELETE FROM cron.job WHERE jobid=p_job_id; RETURN FOUND; END
$$;
CREATE FUNCTION cron.schedule(p_job_name text,p_schedule text,p_command text) RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v_id bigint;
BEGIN
  INSERT INTO cron.job(jobname,schedule,command,active)
  VALUES(p_job_name,p_schedule,p_command,true)
  ON CONFLICT(jobname) DO UPDATE SET schedule=EXCLUDED.schedule,command=EXCLUDED.command,active=true
  RETURNING jobid INTO v_id;
  RETURN v_id;
END
$$;

CREATE TABLE public.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seller_id uuid,
  title text NOT NULL,
  price text NOT NULL,
  category text NOT NULL DEFAULT 'أخرى',
  description text NOT NULL DEFAULT '',
  image_url text,
  image_urls jsonb NOT NULL DEFAULT '[]'::jsonb,
  location_label text NOT NULL DEFAULT '',
  latitude double precision,
  longitude double precision,
  promoted_until timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  seller_email text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'active',
  archived_at timestamptz,
  sold_to uuid,
  sold_at timestamptz
);
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
GRANT SELECT (id,seller_id,title,price,category,description,image_url,image_urls,created_at,updated_at,status,location_label,latitude,longitude,promoted_until) ON public.products TO anon,authenticated;
GRANT INSERT,UPDATE ON public.products TO authenticated;
-- Reproduce legacy hard-delete privilege so the archive migration proves it removes it.
GRANT DELETE ON public.products TO authenticated;
CREATE POLICY ci_products_public_active_read ON public.products FOR SELECT TO anon,authenticated USING (status='active');
CREATE POLICY products_delete_own ON public.products FOR DELETE TO authenticated USING ((SELECT auth.uid())=seller_id);
CREATE POLICY products_insert_own ON public.products FOR INSERT TO authenticated WITH CHECK ((SELECT auth.uid())=seller_id);

