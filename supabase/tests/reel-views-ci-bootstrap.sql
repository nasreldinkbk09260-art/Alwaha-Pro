-- Disposable CI-only schema for reel metrics; does not touch production data.
CREATE TABLE IF NOT EXISTS public.reels (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS public.comments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_id text NOT NULL,
  target_type text NOT NULL DEFAULT 'post',
  user_id uuid NOT NULL,
  content text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.comments ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.comments TO anon, authenticated;
DROP POLICY IF EXISTS ci_reel_comments_public_read ON public.comments;
CREATE POLICY ci_reel_comments_public_read ON public.comments
  FOR SELECT TO anon, authenticated USING (true);
