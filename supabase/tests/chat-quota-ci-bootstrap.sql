-- Ensure both message tables exist in the disposable CI database.
CREATE TABLE IF NOT EXISTS public.messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id uuid NOT NULL, receiver_id uuid NOT NULL, message text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(), read_at timestamptz
);
CREATE TABLE IF NOT EXISTS public.market_messages (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  conversation_id uuid NOT NULL, sender_id uuid NOT NULL, message text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(), read_at timestamptz
);
