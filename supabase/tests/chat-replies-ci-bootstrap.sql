-- CI-only minimal direct-chat schema used to verify real reply references and RLS scope.
CREATE TABLE IF NOT EXISTS public.friend_requests (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,requester_id uuid NOT NULL,target_id uuid NOT NULL,status text NOT NULL DEFAULT 'pending',created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS public.messages (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,sender_id uuid NOT NULL,receiver_id uuid NOT NULL,message text NOT NULL,created_at timestamptz NOT NULL DEFAULT now(),read_at timestamptz);
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.messages TO authenticated;
GRANT USAGE,SELECT ON SEQUENCE public.messages_id_seq TO authenticated;
GRANT SELECT ON public.friend_requests TO authenticated;
DROP POLICY IF EXISTS friend_requests_insert_requester ON public.friend_requests;
CREATE POLICY friend_requests_insert_requester ON public.friend_requests
FOR INSERT TO authenticated
WITH CHECK (
  requester_id=(SELECT auth.uid())
  AND requester_id<>target_id
  AND status='pending'
);
DROP POLICY IF EXISTS messages_select_participant ON public.messages;
CREATE POLICY messages_select_participant ON public.messages FOR SELECT TO authenticated USING ((SELECT auth.uid())=sender_id OR (SELECT auth.uid())=receiver_id);
DROP POLICY IF EXISTS messages_insert_sender_accepted_friends ON public.messages;
CREATE POLICY messages_insert_sender_accepted_friends ON public.messages FOR INSERT TO authenticated WITH CHECK (sender_id=(SELECT auth.uid()) AND receiver_id IS NOT NULL AND EXISTS (SELECT 1 FROM public.friend_requests fr WHERE fr.status='accepted' AND ((fr.requester_id=(SELECT auth.uid()) AND fr.target_id=messages.receiver_id) OR (fr.target_id=(SELECT auth.uid()) AND fr.requester_id=messages.receiver_id))));
DROP POLICY IF EXISTS messages_update_receiver ON public.messages;
CREATE POLICY messages_update_receiver ON public.messages FOR UPDATE TO authenticated USING ((SELECT auth.uid())=receiver_id) WITH CHECK ((SELECT auth.uid())=receiver_id);
DROP POLICY IF EXISTS messages_delete_sender ON public.messages;
CREATE POLICY messages_delete_sender ON public.messages FOR DELETE TO authenticated USING ((SELECT auth.uid())=sender_id);