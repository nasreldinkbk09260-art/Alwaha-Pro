-- ------------------------------------------------------------
-- 10. Admin helper. Set is_admin=true manually for the owner's profile.
-- ------------------------------------------------------------
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1 from public.users
        where id = auth.uid() and is_admin = true
    );
$$;

-- ------------------------------------------------------------
-- 11. Safe directory view: exposes only fields needed by the user directory.
-- The view never exposes passwords (there is no password column in public.users).
-- ------------------------------------------------------------
drop view if exists public.user_directory cascade;
create view public.user_directory as
select
    id,
    first_name,
    last_name,
    case when hide_email then null else identifier end as identifier,
    case when hide_phone then null else phone end as phone,
    avatar_url,
    is_verified,
    created_at
from public.users;

-- The directory is an intentional security-definer view that exposes only
-- the small set of fields needed by the authenticated user directory.
-- Revoke all default/public access before granting SELECT only to authenticated.
revoke all on table public.user_directory from public, anon, authenticated;

