-- ------------------------------------------------------------
-- 2. Profiles linked 1:1 to Supabase Auth
-- ------------------------------------------------------------
create table public.users (
    id uuid primary key references auth.users(id) on delete cascade,
    first_name text not null default '',
    last_name text not null default '',
    identifier text not null unique,
    phone text not null default '',
    gender text not null default 'ذكر',
    birthdate date,
    avatar_url text,
    is_verified boolean not null default false,
    is_admin boolean not null default false,
    hide_email boolean not null default false,
    hide_phone boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint users_gender_check check (gender in ('ذكر','أنثى'))
);

create index users_identifier_idx on public.users(identifier);
create index users_phone_idx on public.users(phone);
create index users_created_at_idx on public.users(created_at desc);

-- Automatically create a profile whenever Auth creates a user.
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.users (
        id, first_name, last_name, identifier, phone, gender, birthdate,
        avatar_url, hide_email, hide_phone
    ) values (
        new.id,
        coalesce(new.raw_user_meta_data->>'first_name',''),
        coalesce(new.raw_user_meta_data->>'last_name',''),
        lower(coalesce(new.email,'')),
        coalesce(new.phone,''),
        coalesce(new.raw_user_meta_data->>'gender','ذكر'),
        case
            when coalesce(new.raw_user_meta_data->>'birthdate','') <> ''
            then (new.raw_user_meta_data->>'birthdate')::date
            else null
        end,
        nullif(new.raw_user_meta_data->>'avatar_url',''),
        coalesce((new.raw_user_meta_data->>'hide_email')::boolean,false),
        coalesce((new.raw_user_meta_data->>'hide_phone')::boolean,true)
    )
    on conflict (id) do update set
        identifier = excluded.identifier;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_auth_user();

-- Keep profile email/phone metadata aligned if Auth changes them.
create or replace function public.handle_auth_user_update()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    update public.users
    set identifier = lower(coalesce(new.email,'')),
        phone = coalesce(new.phone,''),
        updated_at = now()
    where id = new.id;
    return new;
end;
$$;

drop trigger if exists on_auth_user_updated on auth.users;
create trigger on_auth_user_updated
after update of email, phone on auth.users
for each row execute function public.handle_auth_user_update();

