-- Alwaha-Pro — Supabase Auth + real RLS migration
-- Compatible with the revised index.html supplied with this project.
--
-- IMPORTANT:
-- 1) This script removes the old public.users password storage completely.
-- 2) Passwords are handled only by Supabase Auth (auth.users).
-- 3) Existing custom users from the old bigint public.users table cannot have
--    their plaintext password imported into Auth automatically. Those accounts
--    must sign up again (or be migrated manually by an admin through a secure
--    server-side process).
-- 4) The script does NOT touch auth.users itself and does NOT expose service_role.

begin;
set local lock_timeout = '10s';
set local statement_timeout = '120s';

-- ------------------------------------------------------------
-- 1. Remove old application tables/functions that conflict
-- ------------------------------------------------------------
drop view if exists public.user_directory cascade;
drop function if exists public.is_admin() cascade;
drop function if exists public.handle_new_auth_user() cascade;
drop function if exists public.handle_auth_user_update() cascade;
drop function if exists public.set_updated_at() cascade;

drop table if exists public.game_scores cascade;
