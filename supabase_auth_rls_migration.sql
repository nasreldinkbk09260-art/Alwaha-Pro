-- ------------------------------------------------------------
-- 5. Persistent comments for posts and reels
-- target_id is text because the current demo reels use values like reel_1.
-- ------------------------------------------------------------
create table public.comments (
    id bigint generated by default as identity primary key,
    target_id text not null,
    target_type text not null default 'post',
    user_id uuid not null references auth.users(id) on delete cascade,
    author_name text not null default 'مستخدم',
    content text not null,
    created_at timestamptz not null default now(),
    constraint comments_target_type_check check (target_type in ('post','reel')),
    constraint comments_content_length check (char_length(content) between 1 and 2000)
);
create index comments_target_idx on public.comments(target_type, target_id, created_at asc);
create index comments_user_id_idx on public.comments(user_id);

-- ------------------------------------------------------------
-- 6. Real direct messages
-- ------------------------------------------------------------
create table public.messages (
    id bigint generated by default as identity primary key,
    sender_id uuid not null references auth.users(id) on delete cascade,
    receiver_id uuid not null references auth.users(id) on delete cascade,
    message text not null,
    created_at timestamptz not null default now(),
    read_at timestamptz,
    constraint messages_not_self check (sender_id <> receiver_id),
    constraint messages_length check (char_length(message) between 1 and 5000)
);
create index messages_sender_receiver_idx on public.messages(sender_id, receiver_id, created_at desc);
create index messages_receiver_sender_idx on public.messages(receiver_id, sender_id, created_at desc);

-- ------------------------------------------------------------
-- 7. Verification requests
-- ------------------------------------------------------------
create table public.verification_requests (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    reason text not null,
    status text not null default 'pending',
    created_at timestamptz not null default now(),
    reviewed_at timestamptz,
    reviewed_by uuid references auth.users(id) on delete set null,
    constraint verification_status_check check (status in ('pending','approved','rejected'))
);
create index verification_requests_user_idx on public.verification_requests(user_id, created_at desc);
create index verification_requests_status_idx on public.verification_requests(status, created_at desc);

-- ------------------------------------------------------------
-- 8. Notifications / friend requests / reels / game scores
-- These are prepared with real ownership fields for later UI wiring.
-- ------------------------------------------------------------
create table public.notifications (
    id bigint generated by default as identity primary key,
    recipient_id uuid not null references auth.users(id) on delete cascade,
    title text not null,
    body text,
    type text not null default 'info',
    is_read boolean not null default false,
    created_at timestamptz not null default now()
);
create index notifications_recipient_idx on public.notifications(recipient_id, created_at desc);

create table public.friend_requests (
    id bigint generated by default as identity primary key,
    requester_id uuid not null references auth.users(id) on delete cascade,
    target_id uuid not null references auth.users(id) on delete cascade,
    status text not null default 'pending',
    created_at timestamptz not null default now(),
    unique(requester_id, target_id),
    constraint friend_requests_not_self check (requester_id <> target_id),
    constraint friend_requests_status_check check (status in ('pending','accepted','rejected','cancelled'))
);

create table public.reels (
    id bigint generated by default as identity primary key,
    author_id uuid references auth.users(id) on delete set null,
    title text,
    author_name text,
    media_url text,
    likes_count bigint not null default 0,
    comments_count bigint not null default 0,
    created_at timestamptz not null default now()
);
create index reels_created_at_idx on public.reels(created_at desc);

create table public.game_scores (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users(id) on delete cascade,
    game_id text not null,
    score bigint not null default 0,
    created_at timestamptz not null default now()
);
create index game_scores_user_idx on public.game_scores(user_id, game_id);
create index game_scores_game_idx on public.game_scores(game_id, score desc);

-- ------------------------------------------------------------
-- 9. Updated-at trigger
