-- Users: each account can read/update only its own private profile.
create policy users_select_own on public.users for select to authenticated
using ((select auth.uid()) = id);
create policy users_update_own on public.users for update to authenticated
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);
create policy users_delete_own on public.users for delete to authenticated
using ((select auth.uid()) = id);

-- Posts: public read, authenticated create, owner edit/delete.
create policy posts_select_public on public.posts for select to anon, authenticated using (true);
create policy posts_insert_own on public.posts for insert to authenticated
with check ((select auth.uid()) = author_id);
create policy posts_update_own on public.posts for update to authenticated
using ((select auth.uid()) = author_id)
with check ((select auth.uid()) = author_id);
create policy posts_delete_own on public.posts for delete to authenticated
using ((select auth.uid()) = author_id);

-- Products: public read, owner writes.
create policy products_select_public on public.products for select to anon, authenticated using (true);
create policy products_insert_own on public.products for insert to authenticated
with check ((select auth.uid()) = seller_id);
create policy products_update_own on public.products for update to authenticated
using ((select auth.uid()) = seller_id)
with check ((select auth.uid()) = seller_id);
create policy products_delete_own on public.products for delete to authenticated
using ((select auth.uid()) = seller_id);

-- Comments: public read; authenticated users can create/manage their own.
create policy comments_select_public on public.comments for select to anon, authenticated using (true);
create policy comments_insert_own on public.comments for insert to authenticated
with check ((select auth.uid()) = user_id);
create policy comments_update_own on public.comments for update to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);
create policy comments_delete_own on public.comments for delete to authenticated
using ((select auth.uid()) = user_id);

-- Messages: only the two participants can read; sender creates; receiver can mark read.
create policy messages_select_participant on public.messages for select to authenticated
using ((select auth.uid()) = sender_id or (select auth.uid()) = receiver_id);
create policy messages_insert_sender on public.messages for insert to authenticated
with check ((select auth.uid()) = sender_id);
create policy messages_update_receiver on public.messages for update to authenticated
using ((select auth.uid()) = receiver_id)
with check ((select auth.uid()) = receiver_id);
create policy messages_delete_sender on public.messages for delete to authenticated
using ((select auth.uid()) = sender_id);

-- Verification: owner submits/views; admin reviews.
create policy verification_insert_own on public.verification_requests for insert to authenticated
with check ((select auth.uid()) = user_id);
create policy verification_select_own_or_admin on public.verification_requests for select to authenticated
using ((select auth.uid()) = user_id or public.is_admin());
create policy verification_update_admin on public.verification_requests for update to authenticated
using (public.is_admin())
with check (public.is_admin());

-- Notifications: recipient only.
create policy notifications_select_own on public.notifications for select to authenticated
using ((select auth.uid()) = recipient_id);
create policy notifications_update_own on public.notifications for update to authenticated
using ((select auth.uid()) = recipient_id)
with check ((select auth.uid()) = recipient_id);

-- Friend requests: participants only.
create policy friend_requests_select_participant on public.friend_requests for select to authenticated
using ((select auth.uid()) = requester_id or (select auth.uid()) = target_id);
create policy friend_requests_insert_requester on public.friend_requests for insert to authenticated
with check ((select auth.uid()) = requester_id and requester_id <> target_id);
create policy friend_requests_update_participant on public.friend_requests for update to authenticated
using ((select auth.uid()) = requester_id or (select auth.uid()) = target_id)
with check ((select auth.uid()) = requester_id or (select auth.uid()) = target_id);
create policy friend_requests_delete_requester on public.friend_requests for delete to authenticated
using ((select auth.uid()) = requester_id);

-- Reels: public read, authenticated ownership for mutations.
create policy reels_select_public on public.reels for select to anon, authenticated using (true);
create policy reels_insert_own on public.reels for insert to authenticated
with check ((select auth.uid()) = author_id);
create policy reels_update_own on public.reels for update to authenticated
using ((select auth.uid()) = author_id)
with check ((select auth.uid()) = author_id);
create policy reels_delete_own on public.reels for delete to authenticated
using ((select auth.uid()) = author_id);

-- Scores: public read; users write their own scores.
create policy game_scores_select_public on public.game_scores for select to anon, authenticated using (true);
create policy game_scores_insert_own on public.game_scores for insert to authenticated
with check ((select auth.uid()) = user_id);
create policy game_scores_update_own on public.game_scores for update to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);
create policy game_scores_delete_own on public.game_scores for delete to authenticated
using ((select auth.uid()) = user_id);

-- ------------------------------------------------------------
-- 14. Realtime publication for persistent chat/comments.
-- ------------------------------------------------------------
do $$
begin
    begin alter publication supabase_realtime add table public.messages; exception when duplicate_object then null; end;
    begin alter publication supabase_realtime add table public.comments; exception when duplicate_object then null; end;
end $$;

-- ------------------------------------------------------------
-- 15. Bring any existing Auth users into public.users if profiles are missing.
-- This does not migrate old custom-password accounts.
-- ------------------------------------------------------------
insert into public.users (id, first_name, last_name, identifier, phone)
select
    au.id,
    coalesce(au.raw_user_meta_data->>'first_name',''),
    coalesce(au.raw_user_meta_data->>'last_name',''),
    lower(coalesce(au.email,'')),
    coalesce(au.phone,'')
from auth.users au
where au.email is not null
on conflict (id) do nothing;

commit;

